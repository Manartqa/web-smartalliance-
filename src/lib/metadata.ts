import type { Metadata } from "next";
import { getTranslations } from "next-intl/server";
import { siteConfig } from "@/config/site";
import { locales, type Locale } from "@/i18n/routing";

type PageKey = "home" | "about" | "services" | "contact" | "privacy" | "terms";

/** Title and description for a page whose copy does not live under `meta.*`. */
interface PageCopy {
  title: string;
  description: string;
}

/**
 * Ownership tags for Search Console and Bing Webmaster Tools.
 *
 * Both are optional: `undefined` keys are dropped by Next rather than rendered
 * empty, so an unconfigured deployment simply ships no tag. Reading them from
 * the environment means the token can be pasted at deploy time — verification
 * is per-property, so staging and production hold different values.
 */
const verification = {
  google: process.env.NEXT_PUBLIC_GOOGLE_SITE_VERIFICATION || undefined,
  other: process.env.NEXT_PUBLIC_BING_SITE_VERIFICATION
    ? { "msvalidate.01": process.env.NEXT_PUBLIC_BING_SITE_VERIFICATION }
    : undefined,
};

/**
 * Builds per-page metadata plus the hreflang alternates that let search
 * engines pair the two language versions of the same page.
 *
 * `page` names a `meta.*` namespace, or carries the copy itself — the service
 * detail pages build theirs from the service's own messages.
 */
export async function buildMetadata(
  locale: Locale,
  page: PageKey | PageCopy,
  path: string,
): Promise<Metadata> {
  const copy = typeof page === "string" ? await metaCopy(locale, page) : page;
  const title = withoutWordJoiners(copy.title);
  const description = withoutWordJoiners(copy.description);

  const href = (l: string) => `/${l}${path === "/" ? "" : path}`;
  const languages = Object.fromEntries(locales.map((l) => [l, href(l)]));

  // The card generated by `[locale]/opengraph-image.tsx`. It has to be named
  // here rather than left to the file convention: a child segment that
  // declares `openGraph` replaces the parent's whole object, so /about and
  // friends would otherwise ship with no image at all.
  const card = (route: "opengraph-image" | "twitter-image") => ({
    url: `/${locale}/${route}`,
    width: 1200,
    height: 630,
    alt: title,
  });

  return {
    // The title is the largest line in a search result and the strongest
    // on-page ranking signal a marketing page has. It was previously the
    // company name on all four pages, which left every result looking
    // identical and let Google rewrite the titles itself.
    title,
    description,
    metadataBase: new URL(siteConfig.url),
    applicationName: siteConfig.name,
    verification,
    alternates: {
      canonical: href(locale),
      languages: { ...languages, "x-default": href("en") },
    },
    openGraph: {
      title,
      description,
      url: href(locale),
      siteName: siteConfig.name,
      locale: locale === "th" ? "th_TH" : "en_US",
      // The other locale, so a share on a Thai feed can surface the Thai page.
      alternateLocale: locales
        .filter((l) => l !== locale)
        .map((l) => (l === "th" ? "th_TH" : "en_US")),
      type: "website",
      images: [card("opengraph-image")],
    },
    twitter: {
      card: "summary_large_image",
      title,
      description,
      images: [card("twitter-image")],
    },
    robots: {
      index: true,
      follow: true,
      googleBot: {
        index: true,
        follow: true,
        // Defaults cap the snippet and force a thumbnail-sized preview; both
        // are opt-out, and a B2B result reads better with the full snippet.
        "max-snippet": -1,
        "max-image-preview": "large",
        "max-video-preview": -1,
      },
    },
  };
}

/**
 * The copy uses U+2060 (word joiner) to keep "e-Services" from breaking after
 * the hyphen on screen. Outside a rendered heading it only gets in the way —
 * an exact-match search for "e-Services" misses it — so text that leaves the
 * page (titles, descriptions, llms.txt) drops it.
 */
export const withoutWordJoiners = (text: string) => text.replaceAll("⁠", "");

async function metaCopy(locale: Locale, page: PageKey): Promise<PageCopy> {
  const t = await getTranslations({ locale, namespace: `meta.${page}` });
  return { title: t("title"), description: t("description") };
}
